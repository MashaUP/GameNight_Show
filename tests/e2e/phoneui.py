import asyncio
from common import *
from playwright.async_api import async_playwright
fails = []
def ok(c, m):
    print(('OK   ' if c else 'FAIL ') + m)
    if not c: fails.append(m)
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        ctx, host, code = await tv(b, seats=3)
        c1, a = await join(b, code, 'Ada', 0); c2, bb = await join(b, code, 'Bruno', 1)
        await a.screenshot(path='pu_wait.png')
        ok(await a.is_visible('.ph-dock'), 'barra in basso nella sala d’attesa')
        await host.click('#startBtn'); await host.wait_for_selector('#gameName')
        await host.fill('#gameName', 'Codenames'); await host.click('#startPlay')
        await wait_js(a, "!!document.querySelector('.bet-banner')", 8000)
        ok(True, 'invito al pronostico')
        await a.screenshot(path='pu_idle.png')
        await a.click('.ph-dock [data-dock="bet"]'); await a.wait_for_selector('.dock-sheet .bet-opt')
        await a.screenshot(path='pu_bet.png')
        await a.click('.dock-sheet .bet-opt >> nth=1')
        await wait_js(a, "document.querySelector('.dock-sheet .bet-opt[aria-pressed=\"true\"]')!==null")
        ok(True, 'pronostico fatto')
        await a.click('.dock-sheet [data-dockclose]')
        await a.click('.ph-dock [data-dock="score"]'); await a.wait_for_selector('.dock-sheet .sc-btn')
        await a.click('.dock-sheet .sc-btn[data-sc="5"]'); await a.click('.dock-sheet .sc-btn[data-sc="1"]')
        await wait_js(a, "document.querySelector('#scNum').textContent==='6'")
        ok(True, 'segnapunti +6')
        await a.screenshot(path='pu_score.png')
        await a.click('.dock-sheet [data-dockclose]')
        await a.click('.ph-dock [data-dock="sfx"]'); await a.wait_for_selector('.dock-sheet .sfx-btn')
        await a.screenshot(path='pu_sfx.png')
        await a.click('.dock-sheet .sfx-btn >> nth=0')
        await asyncio.sleep(1.0)
        d = db(); rate = d['rooms'][code].get('rate', {})
        ok(any('sfx' in v for v in rate.values()), 'suono inviato alla TV')
        await a.click('.dock-sheet [data-dockclose]')
        # pronostico chiuso: sposto playStart indietro di 6 minuti (solo nel finto db)
        import json, urllib.request
        st = d['rooms'][code]['state']; ps = st['playStart'] - 6 * 60000
        urllib.request.urlopen(urllib.request.Request(BASE + '/__db', data=json.dumps({'op': 'update', 'path': f'rooms/{code}/state', 'value': {'playStart': ps}}).encode(), method='POST')).read()
        await wait_js(bb, "!document.querySelector('.bet-banner')", 8000)
        await bb.click('.ph-dock [data-dock="bet"]'); await bb.wait_for_selector('.dock-sheet .bet-clock.is-closed')
        ok(await bb.eval_on_selector('.dock-sheet .bet-opt', 'e=>e.disabled'), 'pronostico chiuso dopo 5 minuti')
        await bb.screenshot(path='pu_betclosed.png')
        await bb.click('.dock-sheet [data-dockclose]')
        # voto: slider
        await host.click('#openVote'); await a.wait_for_selector('#overall')
        await set_range(a, '#overall', 8)
        await a.screenshot(path='pu_vote.png')
        g = await a.evaluate("""(()=>{const r=document.querySelector('#overall').getBoundingClientRect();const cs=getComputedStyle(document.querySelector('#overall'));const w=r.width;const rem=parseFloat(getComputedStyle(document.documentElement).fontSize);const thumb=1.85*rem+(w-3.7*rem)*7/9;const t=[...document.querySelectorAll('.ticks--giant span')][7].getBoundingClientRect();return {thumb: r.left+thumb, tick: t.left+t.width/2, right:r.right, vw: innerWidth, sw: document.documentElement.scrollWidth}})()""")
        ok(abs(g['thumb'] - g['tick']) < 3, f"numero 8 sotto il cursore ({g['thumb']:.1f} / {g['tick']:.1f})")
        ok(g['sw'] <= g['vw'], f"niente scorrimento orizzontale ({g['sw']} / {g['vw']})")
        ok(not await a.is_visible('.ph-dock'), 'barra nascosta durante il voto')
        await b.close()
    print('ERRORI:', errs or 'nessuno')
    print('FALLITI:', fails or 'nessuno')
asyncio.run(main())
